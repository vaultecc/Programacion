package ejercicio1;

public class Ejercicio1 {

	public static void main(String[] args) {
	
		//Declaramos la variable y usamos el while para que sume un número hasta llegar a 100
		byte num1 = 0;
		
		while (num1 <100) {
			num1++;
			System.out.println(num1);
		}

	}

}
