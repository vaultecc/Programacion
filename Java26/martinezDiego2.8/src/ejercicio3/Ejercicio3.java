package ejercicio3;

public class Ejercicio3 {

	public static void main(String[] args) {
		
		//declaramos la variable y usamos do while para mostrar por pantalla del 100 al 1
		byte num1 = 101;
		do {
			num1--;
			System.out.println(num1);
		} while (num1 >1);

	}

}
