package ejercicio2;

public class Ejercicio2 {

	public static void main(String[] args) {
		
		//Declaramos la variable y usamos do while para llegar del 1 al 100
		byte num1 = 0;
		do {
			num1++;
			System.out.println(num1);
		} while (num1 <100);
		

	}

}
